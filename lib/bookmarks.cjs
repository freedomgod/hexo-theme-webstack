const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const yaml = require('js-yaml');
const { toNavigation } = require('./bookmark-navigation.cjs');
const { legacyNavigation } = require('./bookmark-legacy.cjs');
const { compatibleIcon } = require('./icon-compat.cjs');

const HEADER = '# Generated by hexo-theme-webstack-next from SQLite. Do not edit.\n';
const DEFAULT_DATABASE = '.webstack/bookmarks.sqlite';

function sqlite() {
  try { return require('node:sqlite'); } catch (cause) {
    throw new Error('SQLite bookmarks require Node.js 22.13+ (recommended: Node.js 24 LTS). YAML mode still supports Node.js 20.19+.', { cause });
  }
}

function inside(parent, child) {
  const relative = path.relative(parent, child);
  return relative === '' || (!relative.startsWith(`..${path.sep}`) && relative !== '..' && !path.isAbsolute(relative));
}

// Native realpath follows Windows junctions; the JS implementation on Node 26
// reports them as plain directories, which would let a junction escape .webstack/.
const resolveReal = fs.realpathSync.native || fs.realpathSync;

// Resolve existing ancestors too, so junctions cannot place a database in public content.
function realPath(filename) {
  if (fs.existsSync(filename)) return resolveReal(filename);
  const parent = path.dirname(filename);
  return parent === filename ? filename : path.join(realPath(parent), path.basename(filename));
}

// Hexo prints a thrown error as `FATAL <stack>`, so a wrong path would bury the
// fix under js-yaml/node internals. Keep configuration mistakes to one line.
class BookmarkConfigError extends Error {
  constructor(message, hint) {
    super(hint ? `${message}\n  ${hint}` : message);
    this.name = 'BookmarkConfigError';
    this.stack = `${this.name}: ${this.message}`;
  }
}

function isPrivatePath(base, filename) {
  return inside(path.join(path.resolve(base), '.webstack'), path.resolve(filename));
}

function databasePath(options) {
  const base = path.resolve(options.base);
  const filename = path.resolve(base, options.database || DEFAULT_DATABASE);
  if (fs.existsSync(filename) && fs.statSync(filename).isDirectory()) {
    throw new BookmarkConfigError(`Bookmark database path is a directory: ${filename}`,
      `Point bookmark_db.path at a SQLite file, for example ${DEFAULT_DATABASE}.`);
  }
  // Only source/ and public/ are published; keeping the database out of them is
  // what protects private bookmarks. Every other location is the user's choice.
  const real = realPath(filename);
  for (const directory of [options.sourceDir || path.join(base, 'source'), options.publicDir || path.join(base, 'public')]) {
    if (inside(realPath(directory), real)) {
      throw new BookmarkConfigError(`Bookmark database would be published: ${filename}`,
        `Move bookmark_db.path outside source/ and public/ (the default ${DEFAULT_DATABASE} works) and run the command again.`);
    }
  }
  return filename;
}

function timestamp(date = new Date()) {
  const pad = value => String(value).padStart(2, '0');
  return `${date.getFullYear()}${pad(date.getMonth() + 1)}${pad(date.getDate())}-${pad(date.getHours())}${pad(date.getMinutes())}${pad(date.getSeconds())}`;
}

// A repeated export is a backup, not an edit: keep every previous database and
// give the new one a readable name instead of failing on the collision.
function uniqueDatabasePath(filename, date = new Date()) {
  const directory = path.dirname(filename);
  const extension = path.extname(filename);
  const stem = path.basename(filename, extension);
  const stamp = timestamp(date);
  let candidate = path.join(directory, `${stem}-${stamp}${extension}`);
  for (let index = 2; fs.existsSync(candidate); index++) {
    candidate = path.join(directory, `${stem}-${stamp}-${index}${extension}`);
  }
  return candidate;
}

function ignorePrivateDirectory(base) {
  const ignorePath = path.join(base, '.gitignore');
  const ignore = fs.existsSync(ignorePath) ? fs.readFileSync(ignorePath, 'utf8') : '';
  // Write the ignore rule before creating any personal database.
  if (!ignore.split(/\r?\n/).includes('/.webstack/')) {
    fs.writeFileSync(ignorePath, `${ignore}${ignore && !ignore.endsWith('\n') ? '\n' : ''}# Local WebStack database (including SQLite journal/WAL files)\n/.webstack/\n`);
  }
}

function prepareDatabase(options, mode = 'init') {
  let filename = databasePath(options);
  if (fs.existsSync(filename)) {
    if (mode !== 'export') {
      throw new BookmarkConfigError(`Bookmark database already exists; keep editing it: ${filename}`,
        'Run "hexo bookmarks init" only once, or point bookmark_db.path at another file.');
    }
    filename = uniqueDatabasePath(filename);
  }
  sqlite();
  // Only .webstack/ belongs to the theme. A custom path may live in a repository
  // where this ignore rule would be wrong, so leave it to the user.
  if (isPrivatePath(options.base, filename)) ignorePrivateDirectory(options.base);
  fs.mkdirSync(path.dirname(filename), { recursive: true });
  return filename;
}

function initialize(options) {
  const filename = prepareDatabase(options);
  if (options.sourceDatabase) {
    const source = path.resolve(options.base, options.sourceDatabase);
    const temporary = `${filename}.${randomUUID()}.tmp`;
    const { DatabaseSync } = sqlite();
    let db;
    try {
      db = new DatabaseSync(source, { readOnly: true });
      db.exec('PRAGMA busy_timeout = 3000');
      // SQLite creates a consistent snapshot, including committed WAL content.
      // Copying just the main file could silently lose recent editor changes.
      db.exec(`VACUUM INTO '${temporary.replaceAll("'", "''")}'`);
      readDatabase(temporary);
      fs.copyFileSync(temporary, filename, fs.constants.COPYFILE_EXCL);
    } finally {
      if (db) db.close();
      if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
    }
  } else {
    fs.copyFileSync(path.join(options.themeDir, 'examples', 'bookmarks.sqlite'), filename, fs.constants.COPYFILE_EXCL);
  }
  return filename;
}

function createDatabase(options, categories, bookmarks) {
  // Store compatibility aliases so editor-added FA6 icons also render through FA5.
  const normalized = categories.map(row => ({ ...row, icon: compatibleIcon(row.icon) }));
  // Validate before creating directories or touching any existing files.
  toNavigation(normalized, bookmarks);
  const filename = prepareDatabase(options, 'export');
  const temporary = `${filename}.${randomUUID()}.tmp`;
  const { DatabaseSync } = sqlite();
  let db;
  try {
    fs.copyFileSync(path.join(options.themeDir, 'examples/bookmarks.sqlite'), temporary, fs.constants.COPYFILE_EXCL);
    db = new DatabaseSync(temporary);
    db.exec('PRAGMA foreign_keys = ON; BEGIN; DELETE FROM bookmarks; DELETE FROM categories WHERE parent_id IS NOT NULL; DELETE FROM categories;');
    const category = db.prepare('INSERT INTO categories (id, parent_id, name, icon, sort_order, enabled) VALUES (?, ?, ?, ?, ?, ?)');
    for (const row of normalized) category.run(row.id, row.parent_id, row.name, row.icon, row.sort_order, row.enabled);
    const bookmark = db.prepare('INSERT INTO bookmarks (id, category_id, name, url, img, description, tags, sort_order, enabled) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)');
    for (const row of bookmarks) bookmark.run(row.id, row.category_id, row.name, row.url, row.img, row.description, row.tags || '', row.sort_order, row.enabled);
    db.exec('COMMIT');
    db.close();
    db = null;
    fs.copyFileSync(temporary, filename, fs.constants.COPYFILE_EXCL);
    return filename;
  } finally {
    if (db) db.close();
    if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
  }
}

function readNavigation(options) {
  const filename = databasePath(options);
  if (!fs.existsSync(filename)) {
    throw new BookmarkConfigError(`Bookmark database missing: ${filename}`,
      'Run "hexo bookmarks init" (or "hexo bookmarks export-db") once, and check that bookmark_db.path is correct.');
  }
  return readDatabase(filename);
}

function readDatabase(filename) {
  const { DatabaseSync } = sqlite();
  let db;
  try {
    db = new DatabaseSync(filename, { readOnly: true });
    db.exec('PRAGMA busy_timeout = 3000; PRAGMA query_only = ON; BEGIN');
    const tables = new Set(db.prepare("SELECT name FROM sqlite_master WHERE type = 'table'").all().map(row => row.name));
    let result;
    if (tables.has('category') && tables.has('bookmark') && !tables.has('categories') && !tables.has('bookmarks')) {
      result = legacyNavigation(db);
    } else {
      if (db.prepare('PRAGMA user_version').get().user_version !== 1) {
        throw new Error('Unsupported bookmark database schema version; expected user_version = 1.');
      }
      const categories = db.prepare('SELECT id, parent_id, name, icon, sort_order, enabled FROM categories ORDER BY sort_order, id').all();
      const bookmarks = db.prepare('SELECT id, category_id, name, url, img, description, tags, sort_order, enabled FROM bookmarks ORDER BY sort_order, id').all();
      result = toNavigation(categories, bookmarks);
    }
    db.exec('COMMIT');
    return result;
  } catch (cause) {
    throw new Error(`Cannot read bookmark database ${filename}: ${cause.message}`, { cause });
  } finally { if (db) db.close(); }
}

function writeNavigation(base, navigation) {
  const filename = path.join(base, 'webstack.generated.yml');
  const content = HEADER + yaml.dump(navigation, { noRefs: true, lineWidth: -1, quotingType: '"' });
  if (fs.existsSync(filename)) {
    const previous = fs.readFileSync(filename, 'utf8');
    if (!previous.startsWith(HEADER)) throw new Error(`Refusing to overwrite a user-owned file: ${filename}`);
    if (previous === content) return;
  }
  const temporary = `${filename}.${randomUUID()}.tmp`;
  try {
    fs.writeFileSync(temporary, content, { flag: 'wx' });
    fs.renameSync(temporary, filename);
  } finally {
    if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
  }
}

function exportBookmarks(options) {
  const navigation = readNavigation(options);
  writeNavigation(options.base, navigation);
  return navigation;
}

module.exports = { initialize, readNavigation, writeNavigation, exportBookmarks, createDatabase, isPrivatePath, BookmarkConfigError };
